import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const root = path.resolve(frontend, '..')
const swagger = JSON.parse(await readFile(path.join(root, 'docs/swagger.json'), 'utf8'))

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const full = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await sourceFiles(full))
    else if (/\.(ts|tsx)$/.test(entry.name) && !entry.name.includes('generated')) files.push(full)
  }
  return files
}

const sources = await Promise.all((await sourceFiles(path.join(frontend, 'src'))).map(async file => ({ file: path.relative(root, file).replaceAll('\\', '/'), source: await readFile(file, 'utf8') })))
const clientSource = sources.find(item => item.file.endsWith('/src/api/client.ts'))?.source ?? ''
const endpointsBody = clientSource.match(/export const endpoints\s*=\s*\{([\s\S]*?)\}\s*as const/)?.[1] ?? ''
const endpointMap = new Map([...endpointsBody.matchAll(/\b(\w+)\s*:\s*['"]([^'"]+)['"]/g)].map(([, name, route]) => [name, route]))
const calls = []
const callPattern = /\b(apiFetch|apiPost|uploadFile|downloadFile)\s*(?:<[^()]+>)?\s*\(\s*(`(?:\\.|[^`])*`|'(?:\\.|[^'])*'|"(?:\\.|[^"])*"|endpoints\.\w+)/g

for (const { file, source } of sources) {
  for (const match of source.matchAll(callPattern)) {
    let route = match[2]
    if (route.startsWith('endpoints.')) {
      const property = route.slice('endpoints.'.length)
      route = endpointMap.get(property) ?? ''
    } else route = route.slice(1, -1)
    route = route.replace(/\$\{endpoints\.(\w+)\}/g, (_, property) => endpointMap.get(property) ?? '')
    if (!route.startsWith('/')) continue
    route = route.split('?')[0]
    const optionStart = match.index + match[0].length
    const after = source.slice(optionStart, optionStart + 140)
    let method = match[1] === 'apiPost' || match[1] === 'uploadFile' ? 'POST' : 'GET'
    if (match[1] === 'apiFetch') method = after.match(/method\s*:\s*['"](GET|POST|PUT|DELETE|PATCH)['"]/i)?.[1]?.toUpperCase() ?? 'GET'
    calls.push({ file, method, route: route.replace(/\$\{[^}]+\}/g, '__PARAM__') })
  }
}

if (clientSource.includes("'/auth/refresh-token'")) {
  calls.push({ file: sources.find(item => item.file.endsWith('/src/api/client.ts'))?.file ?? 'src/api/client.ts', method: 'POST', route: '/auth/refresh-token' })
}

const normalizedRoute = route => route.replace(/\{[^}]+\}/g, '__PARAM__')
const rows = []
for (const [route, operations] of Object.entries(swagger.paths)) {
  for (const method of Object.keys(operations).filter(value => ['get', 'post', 'put', 'delete', 'patch'].includes(value))) {
    const clientRoute = route.replace(/^\/api/, '')
    const match = calls.find(call => call.method === method.toUpperCase() && normalizedRoute(clientRoute) === call.route)
    rows.push('| ' + method.toUpperCase() + ' | `' + route + '` | ' + (match ? '\u2705' : '\u274c') + ' | ' + (match ? '`' + match.file + '`' : 'No matching frontend call') + ' |')
  }
}

const content = [
  '# Frontend route inventory',
  '',
  'Generated by `CoachPulse.Frontend/scripts/route-inventory.mjs` from `docs/swagger.json` and literal API client calls under `CoachPulse.Frontend/src`. A check mark means a matching method and route call was found; it does not claim that the UI has been manually exercised against a live database.',
  '',
  '| Method | Backend route | Status | Frontend call site |',
  '|---|---|---|---|',
  ...rows,
  '',
  `Inventory counts: ${rows.filter(row => row.includes('| \u2705 |')).length} matched operations; ${rows.filter(row => row.includes('| \u274c |')).length} not yet consumed by the frontend.`,
  '',
].join('\n')

await writeFile(path.join(root, 'docs/FRONTEND_ROUTE_INVENTORY.md'), content)
console.log(`Wrote ${rows.length} route operations to docs/FRONTEND_ROUTE_INVENTORY.md`)
